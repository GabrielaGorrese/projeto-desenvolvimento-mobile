import { LinearGradient } from 'expo-linear-gradient';

export default function GradientView({ colors, style, children }) {
  return (
    <LinearGradient
      colors={colors}
      start={{ x: 0, y: 0 }}
      end={{ x: 1, y: 1 }}
      style={style}
    >
      {children}
    </LinearGradient>
  );
}